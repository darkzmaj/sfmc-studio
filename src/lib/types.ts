export interface CatalogItem {
  id: number;
  name: string;
  internal: string;
  slot: string;
  classes: string[];
  regions: string[];
  model?: ModelRef;
  icon?: string;
  paintable: boolean;
  styles?: CatalogStyle[];
  hideBodygroups?: string[];
  year?: number;
  holiday?: string;
}
export interface Paint { id: number; name: string; red: [number, number, number]; blu?: [number, number, number] }
export interface PriceSnapshot {
  generatedAt: string;
  currency: string;
  source: string;
  note: string;
  items: Record<string, { p: number; n: number }>;
  paints: Record<string, { p: number; name: string }>;
}
